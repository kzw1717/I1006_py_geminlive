"""設定をまとめたモジュール。

環境変数（.env ファイル）から値を読み込みます。
学生が触りそうな値（モデル名・声・プロンプト）はすべてここに集めています。
"""

import os

from dotenv import load_dotenv

# .env ファイルを読み込む（存在しなくてもエラーにはならない）
load_dotenv()

# --- API キー -------------------------------------------------------------
# GEMINI_API_KEY を優先し、なければ GOOGLE_API_KEY も見る
GEMINI_API_KEY = os.getenv("GEMINI_API_KEY") or os.getenv("GOOGLE_API_KEY")

# --- 使用するモデル -------------------------------------------------------
# Live API（音声の入出力＋文字起こし）に使うモデル。
# モデル名は更新されることがあるので、最新は公式ドキュメントで確認してください。
#   https://ai.google.dev/gemini-api/docs/models
# ※ 使えるモデル名は変わります。エラーになったら、使えるモデルを確認する方法を
#    README の「うまく動かないとき」に記載しています。
LIVE_MODEL = os.getenv("GEMINI_LIVE_MODEL", "gemini-3.1-flash-live-preview")

# 感情分析（テキスト → 構造化JSON）に使うモデル。
# "gemini-flash-latest" は常に最新の flash を指すエイリアスなので壊れにくい。
ANALYSIS_MODEL = os.getenv("GEMINI_ANALYSIS_MODEL", "gemini-flash-latest")

# --- 音声まわり -----------------------------------------------------------
VOICE_NAME = os.getenv("GEMINI_VOICE", "Aoede")  # Gemini の声
LANGUAGE_CODE = "ja-JP"  # 話す言語

# Live API の音声フォーマット（公式仕様で決まっている値なので変更しない）
SEND_SAMPLE_RATE = 16000  # マイク → Gemini は 16kHz
RECV_SAMPLE_RATE = 24000  # Gemini → スピーカーは 24kHz
CHANNELS = 1  # モノラル
CHUNK_FRAMES = 1024  # 一度に読み書きする音声のかたまり（フレーム数）

# 再生音量の調整 -----------------------------------------------------------
# Mac の内蔵スピーカーは、音の出だしで一瞬だけ大きく鳴ってから音量が落ち着く
# ことがあります。各発話の冒頭を少しずつ大きくする「フェードイン」で和らげます。
PLAYBACK_FADE_IN_SECONDS = 1.0  # 冒頭をこの秒数かけて徐々に大きくする（0 で無効）
OUTPUT_GAIN = 1.0  # 全体の音量倍率。大きすぎると感じたら 0.6 など小さくする

# --- プロンプト -----------------------------------------------------------
# Gemini に「どんなインタビュアーか」を教えるシステムプロンプト。
# ここで「キーワードを使って次の質問につなげる」よう指示しているのがポイント。
INTERVIEWER_SYSTEM_PROMPT = """\
あなたは共感的で、聞き上手な日本語の対話型インタビュアーです。
目的は、被験者（あなたと話している相手）の気持ちや考えを引き出すことです。

守ってほしいルール:
- 一度に投げかける質問は「1つだけ」。短く、答えやすい質問にする。
- 被験者の直前の回答に含まれる「印象的なキーワード」を1つ選び、
  そのキーワードに触れながら、感情や背景を深掘りする次の質問につなげる。
- やさしく自然な話し言葉で話す。専門用語は避ける。
- 評価・診断・アドバイスはしない。あくまで傾聴の姿勢で、質問を中心に話す。
- あいづちや前置きは短く。最後は必ず1つの質問で終える。
"""

# 会話のいちばん最初に Gemini へ送る指示（最初の質問を作らせる）。
KICKOFF_PROMPT = """\
これからインタビューを始めます。
被験者がリラックスできるような、やさしい最初の質問を1つだけ、日本語で投げかけてください。
"""

# 感情分析モデルへのシステムプロンプト。
ANALYZER_SYSTEM_PROMPT = """\
あなたは日本語の感情分析の専門家です。
与えられた発話から、話し手の感情を読み取り、指定された JSON 形式で出力してください。
主要な感情ラベルは次の中から最も近いものを1つ選びます:
喜び / 悲しみ / 怒り / 恐れ / 驚き / 嫌悪 / 期待 / 信頼 / 中立
"""
